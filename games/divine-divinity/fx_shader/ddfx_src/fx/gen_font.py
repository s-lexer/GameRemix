"""Bakes DejaVu Sans Mono (free licence, see LICENSE_DEJAVU) 8x16 glyph alpha atlas (ASCII + Cyrillic) into ../inc/fx_font.h"""
import os, sys
from PIL import Image, ImageDraw, ImageFont
H = os.path.dirname(os.path.abspath(__file__)); INC = os.path.join(os.path.dirname(H), 'inc')
TTF = sys.argv[1]
f = ImageFont.truetype(TTF, 13)
cps = list(range(32, 127)) + list(range(0x410, 0x450)) + [0x401, 0x451]
asc, desc = f.getmetrics()
data = []
for cp in cps:
    im = Image.new('L', (8, 16), 0); ImageDraw.Draw(im).text((0, 13 - asc + 1), chr(cp), font=f, fill=255)
    data.append(list(im.tobytes()))
o = ['/* generated by fx/gen_font.py from DejaVu Sans Mono (Bitstream Vera / DejaVu licence) */', '#ifndef FX_FONT_H', '#define FX_FONT_H',
     '#define FXF_W 8', '#define FXF_H 16', '#define FXF_N %d' % len(cps), 'static const unsigned char FX_FONT[FXF_N][FXF_W * FXF_H] = {']
for g in data: o.append('{' + ','.join(str(x) for x in g) + '},')
o += ['};', '#endif']
open(os.path.join(INC, 'fx_font.h'), 'w').write('\n'.join(o) + '\n'); print(len(cps), 'glyphs')
