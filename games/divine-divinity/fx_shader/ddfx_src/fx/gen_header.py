"""Generates ../inc/fx_params.h (param table, presets), ../inc/fx_glsl.h (embedded shader), ../inc/fx_font.h (glyph atlas)"""
import os, sys
H = os.path.dirname(os.path.abspath(__file__)); INC = os.path.join(os.path.dirname(H), 'inc')
sys.path.insert(0, H)
import params as P
def cstr(s):
    out = ''
    for b in s.encode('utf-8'):
        c = chr(b)
        if b >= 128 or b < 32: out += '\\%03o' % b
        elif c in '\\"': out += '\\' + c
        elif c == '?': out += '\\?'
        else: out += c
    return '"' + out + '"'
o = ['/* generated by fx/gen_header.py - do not edit */', '#ifndef FX_PARAMS_H', '#define FX_PARAMS_H', '']
flat = [(si, p) for si, s in enumerate(P.SECTIONS) for p in s[2]]
o.append('#define FX_NP %d' % len(flat)); o.append('#define FX_NSEC %d' % len(P.SECTIONS)); o.append('#define FX_NPRESET %d' % len(P.PRESETS))
o.append('typedef struct { const char* key; const char* ru; const char* en; float mn, mx, st, def; int kind; int sec; } FXPARAM;')
o.append('static const FXPARAM FX_PARAMS[FX_NP] = {')
for si, p in flat:
    o.append('    { %s, %s, %s, %.4ff, %.4ff, %.4ff, %.4ff, %d, %d },' % (cstr(p[0]), cstr(p[1]), cstr(p[2]), p[3], p[4], p[5], p[6], 1 if p[7] == 'b' else 0, si))
o.append('};')
o.append('static const char* FX_SECTIONS_RU[FX_NSEC] = { %s };' % ', '.join(cstr(s[0]) for s in P.SECTIONS))
o.append('static const char* FX_PRESET_NAMES[FX_NPRESET] = { %s };' % ', '.join(cstr(p[0]) for p in P.PRESETS))
o.append('static const char* FX_PRESET_DEFS[FX_NPRESET] = {')
for p in P.PRESETS: o.append('    %s,' % cstr(','.join('%s=%g' % (k, v) for k, v in p[2].items())))
o.append('};')
UI = dict(TITLE='Divine Divinity FX   F10 закрыть', HELP1='Вверх/Вниз выбор  Влево/Вправо знач.  Shift x5  Ctrl /5', HELP2='Ctrl+Shift+1..5 стили вне меню | 1..5 пресет | S сохранить',
          PRESET='Пресеты (1-5)', SAVE='Сохранить в dd-fx.cfg (S)', RESET='Сбросить всё (R)', ON='ВКЛ', OFF='выкл', SAVED='Сохранено', LOADED='Пресет', RESETMSG='Сброшено', SLOT='Слот сохранён', FXON='FX включён', FXOFF='FX выключен (до/после)',
          NOFPS='', DBG0='нет', DBG1='огонь', DBG2='магия', DBG3='свет')
for k, v in UI.items(): o.append('#define FXS_%s %s' % (k, cstr(v)))
o.append('#endif')
open(os.path.join(INC, 'fx_params.h'), 'w', encoding='utf-8').write('\n'.join(o) + '\n')
# glsl: split into <=16000 char pieces (MSVC string literal limit 16380)
g = open(os.path.join(H, 'fx.glsl'), encoding='utf-8').read()
lines = g.split('\n')
body = ['static const char FX_GLSL[] ='] + ['    %s' % cstr(l + '\n') for l in lines] + ['    ;']
open(os.path.join(INC, 'fx_glsl.h'), 'w', encoding='utf-8').write('/* generated from fx/fx.glsl */\n#ifndef FX_GLSL_H\n#define FX_GLSL_H\n' + '\n'.join(body) + '\n#endif\n')
print('headers ok', len(flat), 'params')
