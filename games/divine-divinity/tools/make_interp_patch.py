"""LEGACY (07.11.2026): the live tables (frame, windows, glow, interp) are made by tools/make_exe_patches.py; this tool only produced the old +4096-byte form that gfx.txt keeps as patch=interp_legacy (never use --write).
Строка `patch=interp|...` для gfx.txt: интерполяция кадров (patch_research/interp_patch.py) как таблица байтов + хвост файла.
Запуск (из корня проекта): python games/divine-divinity/tools/make_interp_patch.py [исходный div.exe] [--write]
 - исходный exe: эталон 1.0.0.62 (sha256 cd9f7a07...2a67), по умолчанию scratch/re/div.exe;
 - без --write печатает строку; с --write заменяет/добавляет её в games/divine-divinity/gfx/gfx.txt.
Формат: patch=interp|div.exe|<размер>|<смещение>:<исходные>:<новые>|...|append:<hex хвоста>
Хвост (append) = секция .interp, дописанная в конец файла: exe становится на len(append) байт длиннее (Core.ExeSize + BytePatch.Grow)."""
import sys, os, hashlib, subprocess, tempfile
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.abspath(os.path.join(here, '..', '..', '..'))
SHA = 'cd9f7a07c7a605c21052b3517346c7a63083063fb491276a3e4c9836c9b42a67'
def main(a):
    write = '--write' in a; a = [x for x in a if x != '--write']
    src = a[0] if a else os.path.join(root, 'scratch', 're', 'div.exe')
    o = open(src, 'rb').read()
    if hashlib.sha256(o).hexdigest() != SHA: print('not the reference div.exe 1.0.0.62'); return 2
    out = os.path.join(tempfile.mkdtemp(), 'div_interp.exe')
    r = subprocess.run([sys.executable, os.path.join(root, 'games', 'divine-divinity', 'patch_research', 'interp_patch.py'), src, out], capture_output=True, text=True)
    if r.returncode != 0: print(r.stdout, r.stderr); return 3
    n = open(out, 'rb').read(); base = len(o)
    assert len(n) > base and n[:0] == b''
    pts = []; i = 0
    while i < base:
        if o[i] != n[i]:
            j = i
            while j < base and (o[j] != n[j] or any(o[k] != n[k] for k in range(j, min(base, j + 9)))): j += 1
            pts.append((i, j)); i = j
        else: i += 1
    parts = ['%x:%s:%s' % (s, o[s:e].hex(), n[s:e].hex()) for s, e in pts]
    line = 'patch=interp|div.exe|%d|%s|append:%s' % (base, '|'.join(parts), n[base:].hex())
    print('points', len(pts), 'append', len(n) - base, 'patched sha256', hashlib.sha256(n).hexdigest()[:16])
    if not write: print(line); return 0
    gp = os.path.join(root, 'games', 'divine-divinity', 'gfx', 'gfx.txt'); lines = open(gp, encoding='utf-8').read().split('\n')
    cm = '# Frame interpolation (generated by tools/make_interp_patch.py from patch_research/interp_patch.py; report docs/recon/2026-11-07_interp.md): +%d bytes (section .interp), hooks in %d places; needs gr-draw for >60 FPS' % (len(n) - base, len(pts))
    lines = [l for l in lines if not l.startswith('patch=interp|') and not l.startswith('# Frame interpolation')]
    while lines and lines[-1] == '': lines.pop()
    lines += [cm, line, '']
    open(gp, 'w', encoding='utf-8', newline='').write('\n'.join(lines)); print('written', gp)
    return 0
if __name__ == '__main__': sys.exit(main(sys.argv[1:]))
