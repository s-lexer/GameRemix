        public ArticleForm(Art a)
        {
            Text = a.Title; FormBorderStyle = FormBorderStyle.Sizable; MinimizeBox = false; MaximizeBox = false; ShowInTaskbar = false;
            StartPosition = FormStartPosition.CenterParent; ClientSize = new Size(640, 560); MinimumSize = new Size(480, 360); BackColor = Th.Bg; ForeColor = Th.Text; Font = Th.Body;
