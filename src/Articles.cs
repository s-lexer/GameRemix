            {
                rt.SelectionStart = rt.TextLength; rt.SelectionColor = col; rt.SelectionFont = Th.F("Segoe UI", pt, st);
                rt.SelectionIndent = indent; rt.SelectionHangingIndent = indent > 0 ? 14 : 0; rt.SelectedText = t;
            };
            add(a.Title + "\n", Th.Text, FontStyle.Bold, 13f, 0); add(a.Desc + "\n\n", Th.Muted, FontStyle.Regular, 9f, 0);
            foreach (string raw in a.Body.Replace("\r", "").Split('\n'))
            {
                if (raw.Length == 0) { add("\n", Th.Text, FontStyle.Regular, 5f, 0); continue; }
                if (raw.StartsWith("# ")) add(raw.Substring(2) + "\n", Th.Amber, FontStyle.Bold, 10f, 0);
                else if (raw.StartsWith("- ")) add("•  " + raw.Substring(2) + "\n", Th.Text, FontStyle.Regular, 9.5f, 12);
